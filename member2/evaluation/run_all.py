REPORTS = Path(__file__).resolve().parents[1] / "reports"

# Hand-derived from Member 1's records: which escalations the official policy requires.
MEMBER1_ESCALATIONS = {
    "base": {"NEAR_TIE"},                   # 17,000 (reduce PO-001 by 200) vs 19,000, 20,000, 21,000
    "rev_c_supplier_delay": {"NEAR_TIE"},   # the same choices plus the 12,000 expedite fee
    "excess_rev_b_orders": set(),           # 21,000 (cancel PO-002, reduce PO-001 by 100), next 33,000
    "blocked_supplier": {"NO_FEASIBLE_PLAN"},   # S3 is blocked, S4 unqualified
    "date_conflict": {"INVALID_DATA"},      # no revision permitted in W4 and W5
    "missing_records": {"INVALID_DATA"},
}


def run_evaluation(datasets, expected, base, config=None, simulate=None):
    config = config or load_config()
    simulate = simulate or load_simulator(config)
    results = {name: run_optimization(data, config, simulate) for name, data in datasets.items()}
    valid = [n for n, r in results.items() if r["decision"] != "INVALID_DATA"]
    weekly = []
    for name in valid:
        for plan in results[name]["ranked_plans"]:
            data = apply_plan_actions(make_plan(plan["actions"], datasets[name]), datasets[name])
            weekly.append(run_simulation(data, simulate)["weekly"])
    agreement = [row for n in valid for row in check_solver_agreement(datasets[n], config, simulate)]
    return {
        "config": config, "results": results, "base": base,
        "comparison": {n: compare_configurations(datasets[n], config, simulate, results[n]) for n in valid},
        "solver_rows": agreement,
        "solver_agreement": metrics.solver_agreement(agreement),
        "reconciliation": metrics.inventory_reconciliation(weekly),
        "violations": metrics.hard_rule_violations(results.values()),
        "routing": metrics.escalation_routing(results.values(), expected),
        "replay": metrics.replay_reproducibility(
            [replay_matches(results[n], datasets[n], config, simulate) for n in results]),
    }


def rupees(value):
    """Indian digit grouping: 100000 -> ₹1,00,000."""
    whole = f"{round(value):d}"
    head, tail = whole[:-3], whole[-3:]
    while len(head) > 2:
        head, tail = head[:-2], f"{head[-2:]},{tail}"
    return f"₹{head + ',' if head else ''}{tail}"


def table(headers, rows):
    lines = ["| " + " | ".join(headers) + " |", "|" + " --- |" * len(headers)]
    return "\n".join(lines + ["| " + " | ".join(str(c) for c in row) + " |" for row in rows])


def _note(evaluation):
    simulator = next(iter(evaluation["results"].values()))["simulator"]
    return (f"Generated by `python -m member2.evaluation.run_all`. Synthetic data. Simulator used: "
            f"`{simulator}`. No real-world savings are claimed.")


def optimization_report(ev):
    base = ev["results"][ev["base"]]
    parts = ["# Optimization report", _note(ev), "## Base scenario: top plans",
             f"Decision: **{base['decision']}**. {base['counts']['combinations']} combinations, "
             f"{base['counts']['feasible']} feasible, {base['counts']['rejected']} rejected, "
             f"method {base['method']}, {base['computation_seconds']} s.",
             table(["Rank", "Plan", "Actions", "Shortage", "Excess", "Action cost", "E + C", "Robust"],
                   [[p["rank"], p["plan_id"], p["summary"], p["shortage_units"], rupees(p["excess_value"]),
                     rupees(p["action_cost"]), rupees(p["secondary_cost"]), p["robustness"]["display"]]
                    for p in base["recommendations"]]),
             "Look-alikes that add a no-effect action to a better-ranked plan stay in the full ranking "
             "with `redundant_of` filled in, and are skipped here.",
             "## Best plan per effective week",
             table(["Week", "Best plan", "Shortage", "Excess", "Action cost"],
                   [[f"W{r['effective_week']}", r["summary"], r["shortage_units"],
                     rupees(r["excess_value"]), rupees(r["action_cost"])] if r["plan_id"]
                    else [f"W{r['effective_week']}", "no feasible plan", "-", "-", "-"]
                    for r in base["effective_week_comparison"]]),
             "## Escalations",
             "\n".join(f"- **{e['code']}**: {e['message']}" for e in base["escalations"]) or "None.",
             "## Rejected plans",
             table(["Actions", "Rule", "Reason"],
                   [[", ".join(f"{k}={v}" for a in p["actions"] for k, v in a.items()) or "no change",
                     r["rule"], r["description"]]
                    for p in base["rejected_plans"] for r in p["rejection_reasons"]]),
             "## Every scenario",
             table(["Scenario", "Decision", "Recommended plan", "Shortage", "E + C", "Seconds"],
                   [[n, r["decision"], r["recommendations"][0]["summary"] if r["recommendations"] else "-",
                     r["recommendations"][0]["shortage_units"] if r["recommendations"] else "-",
                     rupees(r["recommendations"][0]["secondary_cost"]) if r["recommendations"] else "-",
                     r["computation_seconds"]] for n, r in ev["results"].items()])]
    return "\n\n".join(parts) + "\n"


def robustness_report(ev):
    parts = ["# Robustness report", _note(ev),
             "Nine runs per plan: Rev C lead time +0/+1/+2 weeks by demand -10%/0/+10%. A run passes when "
             "it has zero shortage. Robustness does not change the official ranking."]
    for name, result in ev["results"].items():
        if not result["recommendations"]:
            continue
        ids = [s["scenario_id"] for s in result["recommendations"][0]["robustness"]["scenarios"]]
        parts += [f"## {name}", table(
            ["Rank", "Plan", "Score"] + ids,
            [[p["rank"], p["summary"],
              f"{p['robustness']['display']} ({p['robustness']['ratio']:.2%})"]
             + [s["shortage_units"] for s in p["robustness"]["scenarios"]]
             for p in result["recommendations"]])]
    return "\n\n".join(parts + ["Cells are shortage units."]) + "\n"


def evaluation_report(ev):
    def pct(m):
        return f"{m['passed']}/{m['total']} ({m['value']:.2%})" if m["total"] else "not run"
    parts = ["# Evaluation report", _note(ev), "## Baselines versus ChangeWise"]
    rows = []
    for name, configurations in ev["comparison"].items():
        rows += [[name, c["configuration"], c["shortage_units"],
                  ", ".join(f"W{w}" for w in c["shortage_weeks"]) or "-", rupees(c["excess_value"]),
                  rupees(c["action_cost"]), rupees(c["secondary_cost"]), c["hard_rule_violations"],
                  c["robustness"]["display"]] for c in configurations]
    parts += [table(["Scenario", "Configuration", "Shortage", "Weeks", "Excess", "Action cost", "E + C",
                     "Rule violations", "Robust"], rows),
              "## Metrics measured by Member 2",
              table(["Metric", "Result"], [
                  ["Hard-rule violations in recommended plans", ev["violations"]],
                  ["Inventory reconciliation, all feasible plans, every week", pct(ev["reconciliation"])],
                  ["Escalation routing, exact code match", pct(ev["routing"])],
                  ["Engine replay, identical output", pct(ev["replay"])],
                  *[[f"Enumeration = {name}", pct(m)] for name, m in ev["solver_agreement"].items()]]),
              "Reconciliation checks the simulator named above.",
              "## Escalation routing",
              table(["Scenario", "Expected", "Actual", "Correct"],
                    [[r["scenario_id"], ", ".join(r["expected"]) or "none",
                      ", ".join(r["actual"]) or "none", r["correct"]] for r in ev["routing"]["rows"]]),
              "## Enumeration versus solver",
              table(["Scenario", "Backend", "Enumeration (S, E + C)", "Solver (S, E + C)", "Agrees"],
                    [[r["scenario_id"], r["backend"], r["enumeration"] or "no plan",
                      r["solver"] or "no plan", r["agrees"]]
                     for r in ev["solver_rows"] if r["status"] == "RUN"]),
              *sorted({f"- {r['status']}" for r in ev["solver_rows"] if r["status"] != "RUN"}),
              "## Metrics owned by Members 1 and 3",
              table(["Metric", "Owner", "Status", "Value"],
                    [[m["metric"], m["owner"], m["status"], m["value"] if m["value"] is not None else "-"]
                     for m in metrics.external_metrics(ev.get("evidence"))])]
    return "\n\n".join(parts) + "\n"


def write_reports(evaluation, directory):
    directory.mkdir(parents=True, exist_ok=True)
    for name, build in (("optimization", optimization_report), ("robustness", robustness_report),
                        ("evaluation", evaluation_report)):
        (directory / f"{name}_report.md").write_text(build(evaluation), encoding="utf-8", newline="\n")


def main(evidence_path=None):
    real = run_evaluation({n: member1_bridge.load_dataset(n) for n in member1_bridge.list_scenarios()},
                          MEMBER1_ESCALATIONS, "base")
    if evidence_path:
        real["evidence"] = json.loads(Path(evidence_path).read_text(encoding="utf-8"))
    write_reports(real, REPORTS)
    write_reports(run_evaluation({n: build() for n, build in seeded.SCENARIOS.items()},
                                 seeded.EXPECTED_ESCALATIONS, "BASE", simulate=seeded_simulator), REPORTS / "seeded")
    print(f"Reports written to {REPORTS}")


if __name__ == "__main__":
    main(*sys.argv[1:2])
