"""Write shared/api-contracts/openapi.json and API_CONTRACT_V1.md from the application: python -m scripts.export_openapi"""
import json
from pathlib import Path

from backend.app.main import app
from backend.app.security.permissions import matrix

OUT = Path(__file__).resolve().parents[1] / "shared" / "api-contracts"

NOTES = """# ChangeWise AI API contract, version 1

Generated by `python -m scripts.export_openapi`. `openapi.json` beside this file is the authoritative contract; the frontend's
types are generated from it (`npm run types`). CI fails when either is out of date.

## Conventions

* Base path `/api/v1`. `/health` and `/ready` are public and unversioned.
* Every other route needs `Authorization: Bearer <Supabase access token>`. The role is read from `app.user_profiles`,
  never from the request or the token.
* Errors: `{"error": {"code", "message", "details", "request_id"}}`. Every response carries `X-Request-ID`.
* Unknown request fields are refused (422), so a client cannot send a role, an identity or a result.
* Lists are paginated with `limit` (1-100) and `offset`.
* `scenario` selects Member 1's data variant and defaults to `base`.

## Differences from the endpoint list in the migration brief, and why

| Brief | Here | Reason |
|---|---|---|
| `POST /ecn/{review_id}/extract` | `POST /ecn/{document_id}/extract` | Member 3 creates the review from the extraction, so the document exists first. |
| `POST /approvals` | not present | Member 3 has no "requested" state. A run with a plan and no decision is pending; `GET /approvals` lists it. |
| `POST /approvals/{approval_id}/decision` | `POST /approvals/{run_id}/decision` | The approval row is the decision, so it cannot exist before it. |
| `POST /actions` | not present | Tasks come only from an approved plan, in the same transaction. A free-form create would bypass that. |
| - | `POST /approvals/{run_id}/modification` | Member 2's verdict on a planner-modified plan. |
| - | `POST /approvals/{approval_id}/close` | Member 3's "close change". |
| - | `/changes`, `/changes/{id}/overview`, `/ecn/samples`, `/ecn/manual`, `/ecn/documents/{id}/url`, `/audit/chain`, `/admin/users` | Needed by the pages. |

Repeating a decision, a confirmation or a close returns 409 and changes nothing. Repeating `POST /planning/optimize` on
unchanged inputs returns the existing undecided run.

"""


def main():
    OUT.mkdir(parents=True, exist_ok=True)
    document = app.openapi()
    (OUT / "openapi.json").write_text(json.dumps(document, indent=1, ensure_ascii=False) + "\n", encoding="utf-8", newline="\n")
    lines = [NOTES, "## Permissions\n", "| Permission | Roles |", "|---|---|"]
    lines += [f"| {p} | {', '.join(r)} |" for p, r in sorted(matrix().items())]
    lines += ["", "`Planner` is the stored role `PRODUCTION_PLANNER`. An action may also be updated only by its owner role or the "
                  "planner; an exception only by the roles listed in its `owner_roles`.", "",
              "## Routes", "", "| Method | Path | Request | Response |", "|---|---|---|---|"]

    def name(schema):
        if "$ref" in schema:
            return schema["$ref"].rpartition("/")[2]
        if schema.get("type") == "array":
            return f"{name(schema['items'])}[]"
        return " / ".join(name(s) for s in schema["anyOf"]) if "anyOf" in schema else schema.get("type", "-")
    for path, operations in document["paths"].items():
        for method, operation in operations.items():
            body = operation.get("requestBody", {}).get("content", {})
            request = next((name(c["schema"]) for c in body.values()), "-")
            ok = next(r for code, r in operation["responses"].items() if code.startswith("2"))
            response = next((name(c["schema"]) for c in ok.get("content", {}).values()), "-")
            lines.append(f"| {method.upper()} | `{path}` | {request} | {response} |")
    (OUT / "API_CONTRACT_V1.md").write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")


if __name__ == "__main__":
    main()
