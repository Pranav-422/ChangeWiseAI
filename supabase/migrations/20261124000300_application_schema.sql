-- Application and workflow records. Source: member3/database/app_schema.sql (SQLite).
--   * rowid keeps SQLite's insertion order, which Member 3's repository sorts by.
--   * JSON (not JSONB) holds the snapshots that are hashed or replayed, so they read back exactly as written.
--   * user_id is filled from the acting user of the transaction, never from a request body.

CREATE TABLE app.document_metadata (
    document_id       TEXT PRIMARY KEY,
    change_id         TEXT NOT NULL REFERENCES core.engineering_changes(change_id),
    scenario_id       TEXT NOT NULL,
    source_kind       TEXT NOT NULL CHECK (source_kind IN ('UPLOAD','TEXT','SAMPLE','MANUAL')),
    original_filename TEXT NOT NULL,
    mime_type         TEXT NOT NULL,
    size_bytes        INTEGER NOT NULL CHECK (size_bytes >= 0),
    sha256            TEXT NOT NULL,
    storage_path      TEXT UNIQUE,            -- NULL for manual entry: there is no document
    extraction_status TEXT NOT NULL DEFAULT 'PENDING' CHECK (extraction_status IN ('PENDING','EXTRACTED','FAILED')),
    extraction_error  TEXT,
    review_id         TEXT,
    uploaded_by       UUID DEFAULT app.acting_user(),
    uploaded_at       TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX idx_document_review ON app.document_metadata(review_id);

CREATE TABLE app.ecn_reviews (
    rowid          BIGINT GENERATED BY DEFAULT AS IDENTITY UNIQUE,
    review_id      TEXT PRIMARY KEY,
    scenario_id    TEXT NOT NULL,
    document_text  TEXT NOT NULL,
    document_hash  TEXT NOT NULL,
    extraction     JSONB NOT NULL,
    fields         JSONB NOT NULL,
    validation     JSONB NOT NULL,
    status         TEXT NOT NULL CHECK (status IN ('NEEDS_REVIEW', 'CONFIRMED')),
    created_by     TEXT NOT NULL,
    created_at     TIMESTAMPTZ NOT NULL,
    confirmed_by   TEXT,
    confirmed_at   TIMESTAMPTZ,
    user_id        UUID DEFAULT app.acting_user(),
    extraction_schema_version TEXT NOT NULL DEFAULT '1'
);
CREATE INDEX idx_reviews_scenario ON app.ecn_reviews(scenario_id, rowid DESC);
ALTER TABLE app.document_metadata ADD FOREIGN KEY (review_id) REFERENCES app.ecn_reviews(review_id);

-- The complete snapshot of a planning run; everything replay needs is in this row.
CREATE TABLE app.planning_runs (
    rowid        BIGINT GENERATED BY DEFAULT AS IDENTITY UNIQUE,
    run_id       TEXT PRIMARY KEY,
    review_id    TEXT NOT NULL REFERENCES app.ecn_reviews(review_id),
    scenario_id  TEXT NOT NULL,
    input_hash   TEXT NOT NULL,
    decision     TEXT NOT NULL,
    dataset      JSON NOT NULL,
    config       JSON NOT NULL,
    result       JSON NOT NULL,
    context      JSON NOT NULL,
    explanation  JSON NOT NULL,
    created_by   TEXT NOT NULL,
    created_at   TIMESTAMPTZ NOT NULL,
    user_id      UUID DEFAULT app.acting_user()
);
CREATE INDEX idx_runs_scenario ON app.planning_runs(scenario_id, rowid DESC);
ALTER TABLE core.candidate_plans ADD FOREIGN KEY (optimization_run_id) REFERENCES app.planning_runs(run_id);

CREATE TABLE app.what_if_requests (
    rowid       BIGINT GENERATED BY DEFAULT AS IDENTITY UNIQUE,
    request_id  TEXT PRIMARY KEY,
    run_id      TEXT NOT NULL REFERENCES app.planning_runs(run_id),
    question    TEXT NOT NULL,
    parameters  JSONB NOT NULL,
    result      JSON NOT NULL,
    created_by  TEXT NOT NULL,
    created_at  TIMESTAMPTZ NOT NULL,
    user_id     UUID DEFAULT app.acting_user()
);
CREATE INDEX idx_what_if_run ON app.what_if_requests(run_id, rowid DESC);

CREATE TABLE app.explanation_records (
    explanation_id TEXT PRIMARY KEY,
    subject_type   TEXT NOT NULL CHECK (subject_type IN ('RUN','WHAT_IF')),
    subject_id     TEXT NOT NULL,
    label          TEXT NOT NULL CHECK (label IN ('AI_GENERATED_VERIFIED','TEMPLATE_GENERATED','AWAITING_REVIEW')),
    source         TEXT NOT NULL,
    content        JSON NOT NULL,          -- sections, draft, facts, warning
    created_by     TEXT NOT NULL,
    created_at     TIMESTAMPTZ NOT NULL DEFAULT now(),
    user_id        UUID DEFAULT app.acting_user()
);
CREATE INDEX idx_explanations_subject ON app.explanation_records(subject_type, subject_id, created_at DESC);

CREATE TABLE app.explanation_verifications (
    explanation_id TEXT PRIMARY KEY REFERENCES app.explanation_records(explanation_id),
    status         TEXT NOT NULL CHECK (status IN ('VERIFIED','AWAITING_REVIEW','REJECTED','NOT_APPLICABLE')),
    detail         JSON
);

CREATE TABLE app.approvals (
    rowid        BIGINT GENERATED BY DEFAULT AS IDENTITY UNIQUE,
    approval_id  TEXT PRIMARY KEY,
    run_id       TEXT NOT NULL UNIQUE REFERENCES app.planning_runs(run_id),  -- one final decision per run
    decision     TEXT NOT NULL CHECK (decision IN ('APPROVED', 'REJECTED')),
    modified     BOOLEAN NOT NULL DEFAULT FALSE,
    plan         JSONB,
    comment      TEXT NOT NULL,
    user_name    TEXT NOT NULL,
    role         TEXT NOT NULL,
    created_at   TIMESTAMPTZ NOT NULL,
    closed_at    TIMESTAMPTZ,
    user_id      UUID DEFAULT app.acting_user()
);

-- A task for a person, created only from an approved plan.
CREATE TABLE app.action_items (
    rowid          BIGINT GENERATED BY DEFAULT AS IDENTITY UNIQUE,
    action_id      TEXT PRIMARY KEY,
    approval_id    TEXT NOT NULL REFERENCES app.approvals(approval_id),
    run_id         TEXT NOT NULL REFERENCES app.planning_runs(run_id),
    summary        TEXT NOT NULL,
    action         JSONB NOT NULL,
    owner_role     TEXT NOT NULL,
    status         TEXT NOT NULL CHECK (status IN ('OPEN', 'IN_PROGRESS', 'DONE')),
    created_at     TIMESTAMPTZ NOT NULL,
    updated_at     TIMESTAMPTZ NOT NULL,
    plan_action_id TEXT REFERENCES core.plan_actions(action_id),
    assignee       TEXT,
    due_week       INTEGER
);
CREATE INDEX idx_actions_run ON app.action_items(run_id);
CREATE INDEX idx_actions_approval ON app.action_items(approval_id);

CREATE TABLE app.action_status_history (
    history_id  BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    action_id   TEXT NOT NULL REFERENCES app.action_items(action_id),
    from_status TEXT,
    to_status   TEXT NOT NULL,
    changed_by  UUID DEFAULT app.acting_user(),
    changed_at  TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX idx_action_history ON app.action_status_history(action_id, history_id);

-- Written in the same statement as the status change, so neither can exist without the other.
CREATE FUNCTION app.record_action_status() RETURNS trigger LANGUAGE plpgsql SET search_path = '' AS $$
BEGIN
    IF TG_OP = 'INSERT' THEN
        INSERT INTO app.action_status_history (action_id, to_status) VALUES (NEW.action_id, NEW.status);
    ELSIF NEW.status IS DISTINCT FROM OLD.status THEN
        INSERT INTO app.action_status_history (action_id, from_status, to_status)
        VALUES (NEW.action_id, OLD.status, NEW.status);
    END IF;
    RETURN NEW;
END $$;
CREATE TRIGGER action_status_history AFTER INSERT OR UPDATE ON app.action_items
FOR EACH ROW EXECUTE FUNCTION app.record_action_status();
