-- Common audit architecture. app.audit_log is the one live, hash-chained log (Member 3's design).
-- Member 1's audit_log has another layout and no chain with it, so its rows are kept as they were.

CREATE TABLE app.audit_log (
    seq            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at     TEXT NOT NULL,          -- text on purpose: it is part of the hashed content
    event_type     TEXT NOT NULL,
    entity_id      TEXT NOT NULL,
    user_name      TEXT NOT NULL,
    role           TEXT NOT NULL,
    payload        JSON NOT NULL,          -- JSON keeps the hashed content exactly as written
    previous_hash  TEXT NOT NULL UNIQUE,   -- two events can never follow the same one
    event_hash     TEXT NOT NULL UNIQUE,
    user_id        UUID DEFAULT app.acting_user(),
    recorded_at    TIMESTAMPTZ NOT NULL DEFAULT now(),
    source         TEXT NOT NULL DEFAULT 'app'
);
CREATE INDEX idx_audit_entity ON app.audit_log(entity_id);
CREATE INDEX idx_audit_type ON app.audit_log(event_type);

CREATE TABLE app.legacy_audit_events (
    source_database TEXT NOT NULL,
    source_event_id BIGINT NOT NULL,
    event_time      TEXT NOT NULL,
    actor           TEXT NOT NULL,
    event_type      TEXT NOT NULL,
    entity_type     TEXT NOT NULL,
    entity_id       TEXT NOT NULL,
    payload_json    TEXT NOT NULL,
    previous_hash   TEXT,
    event_hash      TEXT NOT NULL,
    PRIMARY KEY (source_database, source_event_id)
);

CREATE VIEW app.audit_events WITH (security_invoker = true) AS
    SELECT source, seq AS source_event_id, created_at AS event_time, user_name AS actor, role, event_type,
           entity_id, payload::jsonb AS payload, event_hash FROM app.audit_log
    UNION ALL
    SELECT source_database, source_event_id, event_time, actor, '', event_type, entity_id,
           payload_json::jsonb, event_hash FROM app.legacy_audit_events;

CREATE FUNCTION app.refuse_change() RETURNS trigger LANGUAGE plpgsql SET search_path = '' AS $$
BEGIN
    RAISE EXCEPTION '% is append-only', TG_TABLE_NAME;
END $$;

CREATE TRIGGER audit_no_change BEFORE UPDATE OR DELETE ON app.audit_log
FOR EACH ROW EXECUTE FUNCTION app.refuse_change();
CREATE TRIGGER audit_no_truncate BEFORE TRUNCATE ON app.audit_log
FOR EACH STATEMENT EXECUTE FUNCTION app.refuse_change();
CREATE TRIGGER legacy_audit_no_change BEFORE UPDATE OR DELETE ON app.legacy_audit_events
FOR EACH ROW EXECUTE FUNCTION app.refuse_change();
CREATE TRIGGER history_no_change BEFORE UPDATE OR DELETE ON app.action_status_history
FOR EACH ROW EXECUTE FUNCTION app.refuse_change();

-- A stored run is evidence: its snapshots may not be edited or removed.
CREATE TRIGGER planning_run_no_change BEFORE UPDATE OR DELETE ON app.planning_runs
FOR EACH ROW EXECUTE FUNCTION app.refuse_change();

CREATE TABLE app.replay_records (
    replay_id       TEXT PRIMARY KEY,
    run_id          TEXT NOT NULL REFERENCES app.planning_runs(run_id),
    status          TEXT NOT NULL CHECK (status IN ('MATCHED','DIFFERENT','SNAPSHOT_ALTERED')),
    snapshot_intact BOOLEAN NOT NULL,
    original        JSONB NOT NULL,
    reproduced      JSONB,
    differences     JSONB NOT NULL DEFAULT '[]',
    created_by      TEXT NOT NULL,
    created_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
    user_id         UUID DEFAULT app.acting_user()
);
CREATE INDEX idx_replay_run ON app.replay_records(run_id, created_at DESC);
